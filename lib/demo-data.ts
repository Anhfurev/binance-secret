export function calculatePerformanceStats(account: DemoAccount) {
  const profitFactor =
    (account.avgWin * account.winningTrades) /
      (account.avgLoss * account.losingTrades) || 0;
  const expectancy =
    (account.winRate / 100) * account.avgWin -
    ((100 - account.winRate) / 100) * account.avgLoss;
  const sharpeRatio = account.totalPnlPercent / (account.maxDrawdown || 1);

  return {
    profitFactor: profitFactor.toFixed(2),
    expectancy: expectancy.toFixed(2),
    sharpeRatio: sharpeRatio.toFixed(2),
    avgTradeDuration: "1.5 days",
    tradesPerWeek: (account.totalTrades / 4).toFixed(1),
  };
}
